import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.neighbors import KNeighborsClassifier
from sklearn.svm import SVC
from sklearn.naive_bayes import GaussianNB
from sklearn.metrics import classification_report,confusion_matrix

df=pd.read_csv("/content/creditcard.csv")
df.head()

df.info()

df.describe()

df.isnull().sum()

df.duplicated().sum()

df=df.drop_duplicates()

df.duplicated().sum()

plt.figure(figsize=(12,10))
sns.heatmap(df.corr(),annot=True)
plt.show()

scaler=StandardScaler()
df["scaled_amount"]=scaler.fit_transform(df[["Amount"]])
df["scaled_time"]=scaler.fit_transform(df[["Time"]])
df.drop(["Amount","Time"],axis=1,inplace=True)

fraud=df[df["Class"]==1]
normal=df[df["Class"]==0]

normal=normal.sample(len(fraud),random_state=42)

balanced_df=pd.concat([fraud,normal])

balanced_df.Class.value_counts()

X=balanced_df.drop("Class",axis=1)
y=balanced_df["Class"]

X_train,X_test,y_train,y_test=train_test_split(X,y,test_size=0.3,random_state=42)

models={
    "KNN":KNeighborsClassifier(),
    "SVC":SVC(),
    "NB":GaussianNB()
}

model_predictions = {}
model_probabilities = {}

for name, model in models.items():
  model.fit(X_train, y_train)
  y_pred = model.predict(X_test)

  if hasattr(model, "predict_proba"):
    probability = model.predict_proba(X_test)[:, 1]
  else:

    probability = y_pred

  model_predictions[name] = y_pred
  model_probabilities[name] = probability

"""## Model Evaluation"""

from sklearn.metrics import classification_report, roc_auc_score, f1_score

for name in models.keys():
    y_pred = model_predictions[name]
    probability = model_probabilities[name]

    print(f"\n--- {name} Model Evaluation ---")
    print("Classification Report:")
    print(classification_report(y_test, y_pred))
    print(f"ROC-AUC Score: {roc_auc_score(y_test, probability):.4f}")
    print(f"F1-Score: {f1_score(y_test, y_pred):.4f}")

