import numpy as np
from sklearn.linear_model import LogisticRegression

# 1. Prepare the data
# X = Hours Studied (reshaped to a 2D array for the model)
X = np.array([0.5, 1.0, 1.75, 2.25, 2.5, 2.75, 3.0, 3.25, 3.5, 4.0, 4.5, 5.5]).reshape(-1, 1)

# y = Passed Exam (0 = No, 1 = Yes)
y = np.array([0, 0, 0, 0, 1, 0, 1, 0, 1, 1, 1, 1])

# 2. Initialize and fit the Logistic Regression model
model = LogisticRegression()
model.fit(X, y)

# 3. Test the model with a new value (e.g., 4.25 hours of studying)
new_student = np.array([[4.25]])
prediction = model.predict(new_student)
probability = model.predict_proba(new_student)

print(f"Prediction for 4.25 hours: {'Pass' if prediction[0] == 1 else 'Fail'}")
print(f"Probability of passing: {probability[0][1]:.2%}")

import pandas as pd

# Load the dataset
df = pd.read_csv('/content/Iris (1).csv')

# Inspect the first few rows
print("Dataset Loaded successfully!")
print(df.head())

# 1. Drop 'Id' column because it's just a row index and doesn't help predict species
df = df.drop(columns=['Id'])

# 2. Check for missing (null) values
print("Missing values per column:")
print(df.isnull().sum())

# 3. Check for and remove duplicate rows
duplicate_count = df.duplicated().sum()
print(f"\nFound {duplicate_count} duplicate rows.")
if duplicate_count > 0:
    df = df.drop_duplicates()
    print("Duplicates removed!")

# Verify our clean data shape
print(f"Cleaned dataset shape: {df.shape}")

import seaborn as sns
import matplotlib.pyplot as plt

# Plot pairwise relationships of features colored by Species
sns.pairplot(df, hue='Species', palette='Set2')
plt.suptitle("Iris Feature Relationships", y=1.02)
plt.show()

# 1. Calculate the correlation matrix (only for numeric columns)
numeric_df = df.drop(columns=['Species'])
